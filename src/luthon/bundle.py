from __future__ import annotations
import ast
import os
import subprocess
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Set
from .cli import compile_file
from .native.build_capi import compile_wasi_target


class WasmCodeGenerator(ast.NodeVisitor):
    """Translates a Python AST into a WebAssembly C runner with WASI platform bindings."""

    def __init__(self, lua_payload: str = ""):
        self.lua_payload = lua_payload
        self.functions: List[str] = []
        self.toplevel: List[str] = []
        self.declared_globals: Set[str] = set()
        self.current_locals: Dict[str, str] = {}
        self.current_func_name: Optional[str] = None

    def generate(self, tree: ast.Module) -> str:
        for stmt in tree.body:
            if isinstance(stmt, ast.FunctionDef):
                self.visit_FunctionDef(stmt)
            else:
                s = self.visit_stmt(stmt, is_toplevel=True)
                if s:
                    self.toplevel.append(s)

        lines = [
            '/* Automatically generated by Luthon WASM Bundler (Phase 41) */',
            '#include "wasi.h"',
            '#include <stdint.h>',
            '#include <stdbool.h>',
            '',
        ]

        # Declare globals
        for g in sorted(self.declared_globals):
            lines.append(f'static int64_t {g} = 0;')
        if self.declared_globals:
            lines.append('')

        # Embedded transpiled payload
        escaped_payload = (
            self.lua_payload.replace('\\', '\\\\')
            .replace('"', '\\"')
            .replace('\n', '\\n"\n    "')
        )
        lines.append(f'static const char g_luthon_payload[] =\n    "{escaped_payload}";\n')
        lines.append('__attribute__((export_name("luthon_get_payload")))')
        lines.append('const char* luthon_get_payload(void) { return g_luthon_payload; }')
        lines.append('')
        lines.append('__attribute__((export_name("luthon_get_payload_size")))')
        lines.append('uint32_t luthon_get_payload_size(void) { return (uint32_t)(sizeof(g_luthon_payload) - 1); }')
        lines.append('')

        # Functions
        lines.extend(self.functions)
        lines.append('')

        # Main entrypoint
        lines.append('void luthon_main(void) {')
        for stmt in self.toplevel:
            lines.append(f'    {stmt}')
        lines.append('}')
        lines.append('')

        # WASI entrypoint
        lines.append('__attribute__((export_name("_start")))')
        lines.append('void _start(void) {')
        lines.append('    luthon_main();')
        lines.append('}')
        lines.append('')

        # Browser WASM entrypoint
        lines.append('__attribute__((export_name("luthon_init")))')
        lines.append('int luthon_init(void) {')
        lines.append('    luthon_main();')
        lines.append('    return 0;')
        lines.append('}')

        return '\n'.join(lines)

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        self.current_func_name = node.name
        self.current_locals = {}
        params = []
        for a in node.args.args:
            self.current_locals[a.arg] = 'int64_t'
            params.append(f'int64_t {a.arg}')

        body_lines = []
        for s in node.body:
            bs = self.visit_stmt(s, is_toplevel=False)
            if bs:
                body_lines.append(bs)

        param_str = ', '.join(params) if params else 'void'
        fn_lines = [
            f'__attribute__((export_name("{node.name}")))',
            f'int64_t {node.name}({param_str}) {{',
        ]
        # Declare locals not in params
        for loc in sorted(self.current_locals):
            if loc not in [a.arg for a in node.args.args]:
                fn_lines.append(f'    int64_t {loc} = 0;')
        for b in body_lines:
            fn_lines.append(f'    {b}')
        fn_lines.append('}')
        self.functions.append('\n'.join(fn_lines))
        self.current_func_name = None

    def visit_stmt(self, node: ast.stmt, is_toplevel: bool = False) -> str:
        if isinstance(node, ast.Return):
            val = self.visit_expr(node.value) if node.value else '0'
            return f'return {val};'

        elif isinstance(node, ast.Assign):
            target = node.targets[0]
            if isinstance(target, ast.Name):
                name = target.id
                if is_toplevel:
                    self.declared_globals.add(name)
                else:
                    self.current_locals[name] = 'int64_t'
                return f'{name} = {self.visit_expr(node.value)};'
            elif isinstance(target, ast.Tuple):
                temp_vars = []
                assignments = []
                for i, elt in enumerate(target.elts):
                    tname = f'__tmp_{i}'
                    val_expr = (
                        self.visit_expr(node.value.elts[i])
                        if isinstance(node.value, ast.Tuple) and i < len(node.value.elts)
                        else '0'
                    )
                    temp_vars.append(f'int64_t {tname} = {val_expr};')
                for i, elt in enumerate(target.elts):
                    if isinstance(elt, ast.Name):
                        if is_toplevel:
                            self.declared_globals.add(elt.id)
                        else:
                            self.current_locals[elt.id] = 'int64_t'
                        assignments.append(f'{elt.id} = __tmp_{i};')
                return ' '.join(temp_vars + assignments)

        elif isinstance(node, ast.AugAssign):
            op_sym = {
                ast.Add: '+', ast.Sub: '-', ast.Mult: '*', ast.Div: '/',
                ast.Mod: '%', ast.BitAnd: '&', ast.BitOr: '|', ast.BitXor: '^'
            }.get(type(node.op), '+')
            return f'{node.target.id} {op_sym}= {self.visit_expr(node.value)};'

        elif isinstance(node, ast.If):
            test = self.visit_expr(node.test)
            body = ' '.join(self.visit_stmt(s, is_toplevel) for s in node.body)
            if node.orelse:
                orelse = ' '.join(self.visit_stmt(s, is_toplevel) for s in node.orelse)
                return f'if ({test}) {{ {body} }} else {{ {orelse} }}'
            return f'if ({test}) {{ {body} }}'

        elif isinstance(node, ast.While):
            test = self.visit_expr(node.test)
            body = ' '.join(self.visit_stmt(s, is_toplevel) for s in node.body)
            return f'while ({test}) {{ {body} }}'

        elif isinstance(node, ast.For):
            if isinstance(node.target, ast.Name):
                var = node.target.id
                if is_toplevel:
                    self.declared_globals.add(var)
                else:
                    self.current_locals[var] = 'int64_t'

                if isinstance(node.iter, ast.Call) and isinstance(node.iter.func, ast.Name) and node.iter.func.id == 'range':
                    r_args = node.iter.args
                    if len(r_args) == 1:
                        start, stop, step = '0', self.visit_expr(r_args[0]), '1'
                    elif len(r_args) == 2:
                        start, stop, step = self.visit_expr(r_args[0]), self.visit_expr(r_args[1]), '1'
                    else:
                        start, stop, step = self.visit_expr(r_args[0]), self.visit_expr(r_args[1]), self.visit_expr(r_args[2])
                    body = ' '.join(self.visit_stmt(s, is_toplevel) for s in node.body)
                    return f'for ({var} = {start}; {var} < {stop}; {var} += {step}) {{ {body} }}'

        elif isinstance(node, ast.Expr):
            if isinstance(node.value, ast.Call):
                call = node.value
                if isinstance(call.func, ast.Name) and call.func.id == 'print':
                    prints = []
                    for i, arg in enumerate(call.args):
                        if i > 0:
                            prints.append('luthon_wasi_print(" ");')
                        if isinstance(arg, ast.Constant) and isinstance(arg.value, str):
                            esc = arg.value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
                            prints.append(f'luthon_wasi_print("{esc}");')
                        elif isinstance(arg, ast.Constant) and isinstance(arg.value, float):
                            prints.append(f'luthon_wasi_print_double({arg.value}, 6);')
                        else:
                            val_expr = self.visit_expr(arg)
                            prints.append(f'luthon_wasi_print_int({val_expr});')
                    prints.append('luthon_wasi_println("");')
                    return ' '.join(prints)
                else:
                    return f'{self.visit_expr(node.value)};'

        return ''

    def visit_expr(self, node: ast.expr) -> str:
        if isinstance(node, ast.Constant):
            if isinstance(node.value, bool):
                return '1' if node.value else '0'
            elif isinstance(node.value, (int, float)):
                return str(node.value)
            elif isinstance(node.value, str):
                esc = node.value.replace('\\', '\\\\').replace('"', '\\"')
                return f'"{esc}"'
            elif node.value is None:
                return '0'

        elif isinstance(node, ast.Name):
            return node.id

        elif isinstance(node, ast.BinOp):
            left = self.visit_expr(node.left)
            right = self.visit_expr(node.right)
            op_sym = {
                ast.Add: '+', ast.Sub: '-', ast.Mult: '*', ast.Div: '/',
                ast.FloorDiv: '/', ast.Mod: '%', ast.BitAnd: '&',
                ast.BitOr: '|', ast.BitXor: '^', ast.LShift: '<<', ast.RShift: '>>'
            }.get(type(node.op), '+')
            return f'({left} {op_sym} {right})'

        elif isinstance(node, ast.UnaryOp):
            operand = self.visit_expr(node.operand)
            if isinstance(node.op, ast.USub):
                return f'(-{operand})'
            if isinstance(node.op, ast.Not):
                return f'(!{operand})'
            if isinstance(node.op, ast.Invert):
                return f'(~{operand})'

        elif isinstance(node, ast.BoolOp):
            op_sym = ' && ' if isinstance(node.op, ast.And) else ' || '
            vals = [f'({self.visit_expr(v)})' for v in node.values]
            return f'({op_sym.join(vals)})'

        elif isinstance(node, ast.Compare):
            left = self.visit_expr(node.left)
            cmp_ops = {
                ast.Eq: '==', ast.NotEq: '!=', ast.Lt: '<',
                ast.LtE: '<=', ast.Gt: '>', ast.GtE: '>='
            }
            op_sym = cmp_ops.get(type(node.ops[0]), '==')
            right = self.visit_expr(node.comparators[0])
            return f'({left} {op_sym} {right})'

        elif isinstance(node, ast.Call):
            if isinstance(node.func, ast.Name):
                fname = node.func.id
                if fname == 'abs':
                    val = self.visit_expr(node.args[0])
                    return f'(({val}) < 0 ? -({val}) : ({val}))'
                elif fname == 'min':
                    a = self.visit_expr(node.args[0])
                    b = self.visit_expr(node.args[1])
                    return f'(({a}) < ({b}) ? ({a}) : ({b}))'
                elif fname == 'max':
                    a = self.visit_expr(node.args[0])
                    b = self.visit_expr(node.args[1])
                    return f'(({a}) > ({b}) ? ({a}) : ({b}))'
                else:
                    args = [self.visit_expr(a) for a in node.args]
                    return f'{fname}({", ".join(args)})'

        return '0'


class StandaloneBundler:
    """Packages a transpiled Python program and its Luthon runtime prelude into a self-contained executable bundle."""

    def __init__(self, optimize: bool = True, target: str = "native"):
        self.optimize = optimize
        self.target = target

    def build_bundle(self, input_py_path: Path, output_exe_path: Path) -> Path:
        """Transpiles input Python source and writes an executable bundle for the target platform."""
        input_py_path = Path(input_py_path).resolve()
        output_exe_path = Path(output_exe_path).resolve()

        lua_code, _ = compile_file(
            input_path=input_py_path,
            use_ir=True,
            optimize=self.optimize,
            no_cache=True
        )

        if self.target == "native":
            # Generate self-executing standalone amalgamation for host LuaJIT
            shebang = "#!/bin/sh\n"
            launcher = 'exec luajit - "$@" << \'__LUTHON_BUNDLE_EOF__\'\n'
            closing = "\n__LUTHON_BUNDLE_EOF__\n"

            bundle_content = shebang + launcher + lua_code + closing

            output_exe_path.write_text(bundle_content)
            output_exe_path.chmod(output_exe_path.stat().st_mode | 0o755)
            return output_exe_path

        elif self.target in ("wasi", "wasm", "browser"):
            # Generate standalone WebAssembly / WASI binary bundle (.wasm)
            py_source = input_py_path.read_text(encoding="utf-8")
            tree = ast.parse(py_source, filename=str(input_py_path))

            gen = WasmCodeGenerator(lua_payload=lua_code)
            c_runner_code = gen.generate(tree)

            with tempfile.NamedTemporaryFile("w", suffix="_wasm_runner.c", delete=False) as f:
                f.write(c_runner_code)
                runner_c_path = Path(f.name)

            native_dir = Path(__file__).parent / "native"
            wasi_c = (native_dir / "platform" / "wasi.c").resolve()

            entrypoint = "_start" if self.target == "wasi" else None
            try:
                compile_wasi_target(
                    output_path=output_exe_path,
                    sources=[wasi_c, runner_c_path],
                    entrypoint=entrypoint,
                    force=True
                )
            finally:
                if runner_c_path.exists():
                    runner_c_path.unlink()

            return output_exe_path

        else:
            raise ValueError(f"Unknown compilation target: {self.target}. Choose from 'native', 'wasi', 'wasm'.")
